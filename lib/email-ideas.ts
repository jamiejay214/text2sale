export function ideasFor(industry: string | null | undefined): EmailIdea[] {
  const id = industry || "other";
  return [...EMAIL_IDEAS].sort((a, b) => {
    const score = (i: EmailIdea) => (i.industries === "all" ? 1 : i.industries.includes(id) ? 2 : 0);
    return score(b) - score(a);
  });
}
